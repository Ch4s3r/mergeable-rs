import {execFileSync} from 'node:child_process';
import {readFileSync, writeFileSync} from 'node:fs';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';

const websiteDirectory = join(dirname(fileURLToPath(import.meta.url)), '..');
const repositoryRoot = join(websiteDirectory, '..');
const inventoryPage = join(websiteDirectory, 'docs', 'contributing', 'licenses.md');

function shippedRustCrates() {
  const treeOutput = execFileSync(
    'cargo',
    ['tree', '--locked', '--edges', 'normal', '--target', 'all', '--prefix', 'none', '--format', '{p}|{l}'],
    {cwd: repositoryRoot, encoding: 'utf8'},
  );
  const cratesByName = new Map();
  for (const line of treeOutput.split('\n')) {
    const [packageId, licenseExpression] = line.replace(/ \(\*\)$/, '').split('|');
    if (!licenseExpression) continue;
    const [name, version] = packageId.split(' ');
    if (name === 'mergeable') continue;
    cratesByName.set(`${name}@${version}`, {name, version: version.replace(/^v/, ''), license: licenseExpression.trim()});
  }
  return [...cratesByName.values()].sort((left, right) => left.name.localeCompare(right.name) || left.version.localeCompare(right.version));
}

function documentationSitePackages() {
  const lockFile = JSON.parse(readFileSync(join(websiteDirectory, 'package-lock.json'), 'utf8'));
  return Object.entries(lockFile.packages)
    .filter(([path]) => path !== '')
    .map(([, entry]) => ({license: entry.license ?? 'unknown'}));
}

function countBy(items, keyOf) {
  const counts = new Map();
  for (const item of items) counts.set(keyOf(item), (counts.get(keyOf(item)) ?? 0) + 1);
  return [...counts.entries()].sort(([leftKey, leftCount], [rightKey, rightCount]) => rightCount - leftCount || leftKey.localeCompare(rightKey));
}

function countTable(heading, counts) {
  return [`| ${heading} | Packages |`, '|---|---|', ...counts.map(([key, count]) => `| ${key} | ${count} |`)].join('\n');
}

function renderPage(rustCrates, npmPackages) {
  const crateRows = rustCrates.map((crate) => `| ${crate.name} | ${crate.version} | ${crate.license} |`);
  return `---
title: Licenses
---

# Licenses

mergeable-rs is licensed under AGPL-3.0-only, like the original mergeable it was ported from (see ADR-017 in
\`DECISIONS.md\`). This page lists the licenses of the third-party code we ship. It is generated by
\`website/scripts/license-inventory.mjs\` (\`npm run licenses\` in \`website/\`, or \`devenv shell -- license-inventory\`)
from \`Cargo.lock\` and \`website/package-lock.json\`, and regenerated by the docs workflow before every build of this
site.

## License check

\`cargo deny check\` runs in \`devenv test\` and therefore in the \`test\` job of every pull request. It is configured
in \`deny.toml\`:

| Check | Rule |
|---|---|
| licenses | every crate must be available under at least one license of the allowlist: Apache-2.0, BSD-3-Clause, BSL-1.0, CDLA-Permissive-2.0, ISC, MIT, Unicode-3.0, Zlib. All of them are compatible with AGPL-3.0-only. Our own (unpublished) crate is not checked. |
| advisories | the [RustSec advisory database](https://rustsec.org) has no vulnerability, unmaintained or unsound advisory and no yanked version for any crate in \`Cargo.lock\`, except the ignored advisories listed with their reason in \`deny.toml\` |
| bans | duplicate versions of a crate are reported as warnings; wildcard version requirements are rejected |
| sources | crates come from crates.io only; no other registry and no git dependencies |

Run it locally with \`devenv shell -- cargo deny check\`. A new dependency under a license outside the allowlist fails
the check: decide whether the license is compatible with AGPL-3.0-only before adding it to \`deny.toml\`.

## Rust crates in the binary

The \`mergeable\` binary is built from ${rustCrates.length} third-party crates (normal dependencies, including proc-macro crates
and crates for other target platforms, without development dependencies). An expression with \`OR\` means we may use the crate under either license.

${countTable('License expression', countBy(rustCrates, (crate) => crate.license))}

<details>
<summary>All crates</summary>

| Crate | Version | License |
|---|---|---|
${crateRows.join('\n')}

</details>

## Documentation site (npm)

The npm packages in \`website/package-lock.json\` build this documentation site; none of them is part of the binary or
the container image. The published site bundles parts of React, Docusaurus and their runtime dependencies.
${npmPackages.length} packages by the license recorded in the lock file:

${countTable('License', countBy(npmPackages, (npmPackage) => npmPackage.license))}

## Container image

The image is built by Paketo buildpacks (\`project.toml\`) on the Paketo Ubuntu base and run images. Their operating
system packages keep their own licenses (mostly GPL, LGPL, MIT and BSD) and are aggregated with mergeable, not linked
into it. The image carries the label \`org.opencontainers.image.licenses=AGPL-3.0-only\` for mergeable itself.
`;
}

writeFileSync(inventoryPage, renderPage(shippedRustCrates(), documentationSitePackages()));
